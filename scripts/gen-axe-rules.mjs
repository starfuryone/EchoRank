#!/usr/bin/env node
// Generates packages/crawl-rules/src/generated/axe-rules.ts from axe-core's own
// rule metadata, so the accessibility family's names, descriptions and kinds
// are axe's words, not hand-typed ones (SITE-CRAWLER-PHASE3.md, 3b).
//
//   node scripts/gen-axe-rules.mjs
//
// The output is committed. The sidecar (av-service/render.py) runs the SAME
// rule selection from the SAME axe version; bump AXE_VERSION here and the
// vendored av-service/vendor/axe.min.js together, then re-run this.

import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const AXE_VERSION = "4.11.4";
const TAGS = ["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "best-practice"];

const require = createRequire(import.meta.url);
const axe = require("axe-core");
if (axe.version !== AXE_VERSION) {
  console.error(`axe-core is ${axe.version}; this generator is pinned to ${AXE_VERSION}.`);
  process.exit(1);
}

const impacts = new Map(axe._audit.rules.map((r) => [r.id, r.impact ?? null]));
const rules = axe
  .getRules(TAGS)
  .filter((r) => !r.tags.includes("experimental") && !r.tags.includes("deprecated"))
  .map((r) => ({
    axeId: r.ruleId,
    impact: impacts.get(r.ruleId) ?? "moderate",
    help: r.help,
    description: r.description,
    helpUrl: r.helpUrl.replace(/\?.*$/, ""),
    wcag: r.tags.filter((t) => /^wcag\d/.test(t) && !/^wcag\d+a+$/.test(t)).sort(),
    bestPractice: r.tags.includes("best-practice"),
  }))
  .sort((a, b) => a.axeId.localeCompare(b.axeId));

const out = `// GENERATED by scripts/gen-axe-rules.mjs from axe-core ${AXE_VERSION}. Do not edit.
// ${rules.length} rules: tags ${TAGS.join(", ")}; experimental and deprecated excluded.

export const AXE_VERSION = ${JSON.stringify(AXE_VERSION)};

export interface AxeRuleMeta {
  axeId: string;
  impact: "critical" | "serious" | "moderate" | "minor";
  help: string;
  description: string;
  helpUrl: string;
  /** WCAG success-criterion tags, e.g. "wcag111". */
  wcag: string[];
  bestPractice: boolean;
}

export const AXE_RULES: readonly AxeRuleMeta[] = ${JSON.stringify(rules, null, 2)};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "../packages/crawl-rules/src/generated/axe-rules.ts");
writeFileSync(target, out);
console.log(`wrote ${rules.length} rules to ${target}`);
